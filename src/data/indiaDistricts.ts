export const INDIA_STATE_NAMES = Array.from(new Set(INDIA_DISTRICT_CATALOG.map((district) => district.state))).sort((a, b) => a.localeCompare(b));

export const DISTRICTS_BY_STATE: Readonly<Record<string, readonly IndiaDistrict[]>> = Object.freeze(INDIA_STATE_NAMES.reduce<Record<string, IndiaDistrict[]>>((groups, state) => {
  groups[state] = INDIA_DISTRICT_CATALOG.filter((district) => district.state === state);
  return groups;
}, {}));

export const INDIAN_LOCATIONS: Readonly<Record<string, readonly string[]>> = Object.freeze(Object.fromEntries(INDIA_STATE_NAMES.map((state) => [state, DISTRICTS_BY_STATE[state].map((district) => district.name)])));

function localScriptMatchesLanguage(value: string, language: string): boolean {
  const codePoint = value.codePointAt(0) || 0;
  const ranges: Record<string, [number, number][]> = {
    hi: [[0x0900, 0x097f]], mr: [[0x0900, 0x097f]], sa: [[0x0900, 0x097f]],
    doi: [[0x0900, 0x097f]], mai: [[0x0900, 0x097f]], ne: [[0x0900, 0x097f]],
    brx: [[0x0900, 0x097f]], gom: [[0x0900, 0x097f]], ks: [[0x0900, 0x097f]],
    bn: [[0x0980, 0x09ff]], as: [[0x0980, 0x09ff]],
    gu: [[0x0a80, 0x0aff]], pa: [[0x0a00, 0x0a7f]],
    or: [[0x0b00, 0x0b7f]], ta: [[0x0b80, 0x0bff]], te: [[0x0c00, 0x0c7f]],
    kn: [[0x0c80, 0x0cff]], ml: [[0x0d00, 0x0d7f]],
    ar: [[0x0600, 0x06ff]], ur: [[0x0600, 0x06ff]], sd: [[0x0600, 0x06ff]],
    mni: [[0xabc0, 0xabff]], sat: [[0x1c50, 0x1c7f]],
  };
  return (ranges[language] || []).some(([start, end]) => codePoint >= start && codePoint <= end);
}

export function getDistrictDisplayName(district: IndiaDistrict, language: string): string {
  // LGD local-script names are the only names we can safely display without
  // inventing translations for official administrative proper nouns.
  if (district.localName && localScriptMatchesLanguage(district.localName, language)) {
    return district.localName;
  }
  return district.name;
}
